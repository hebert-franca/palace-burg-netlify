create table if not exists public.pb_users (
 id bigint generated by default as identity primary key,
 name text not null,
 email text not null unique,
 role text not null check (role in ('admin','atendente','motoboy')),
 password_hash text not null,
 active boolean not null default true
);
create table if not exists public.pb_products (
 id bigint generated by default as identity primary key,
 name text not null, description text not null default '',
 price numeric(12,2) not null check(price>0),
 category text not null default 'Lanches',photo text not null default '',active boolean not null default true
);
create table if not exists public.pb_store (
 key text primary key, value text not null
);
insert into public.pb_store(key,value) values ('minimum_order','20'),('hours','18:00 - 02:00') on conflict(key) do nothing;
create table if not exists public.pb_orders (
 id bigint generated by default as identity primary key,
 customer text not null,phone text not null default '',address text not null,
 distance numeric(10,2) not null default 0,fee numeric(12,2) not null default 0,
 subtotal numeric(12,2) not null,total numeric(12,2) not null,
 payment text not null check(payment in ('Pix','Dinheiro','Crédito','Débito')),
 status text not null default 'Recebido', driver_id bigint references public.pb_users(id),
 created timestamptz not null default now()
);
create table if not exists public.pb_order_items (
 id bigint generated by default as identity primary key,
 order_id bigint not null references public.pb_orders(id) on delete cascade,
 name text not null,qty integer not null check(qty>0),price numeric(12,2) not null
);

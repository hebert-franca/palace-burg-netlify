-- A transação revalida preços e calcula valores no banco, sem confiar no navegador.
create or replace function public.pb_place_order(
 p_customer text,p_phone text,p_address text,p_payment text,
 p_items jsonb,p_delivery boolean,p_distance numeric,p_fee numeric,p_require_minimum boolean
) returns jsonb
language plpgsql security invoker set search_path = public
as $$
declare v_sub numeric(12,2):=0;v_total numeric(12,2);v_min numeric(12,2);v_order bigint;v_rec record;v_prod record;v_qty integer;
begin
 if length(trim(p_customer))<2 or p_payment not in ('Pix','Dinheiro','Crédito','Débito') then raise exception 'Pedido inválido';end if;
 if p_delivery and (length(trim(p_phone))<8 or length(trim(p_address))<10) then raise exception 'Dados de entrega inválidos';end if;
 if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)<1 or jsonb_array_length(p_items)>100 then raise exception 'Carrinho inválido';end if;
 if p_fee<0 or p_distance<0 then raise exception 'Distância ou frete inválido';end if;
 for v_rec in select * from jsonb_array_elements(p_items) loop
  v_qty := (v_rec.value->>'qty')::integer;
  if v_qty<1 or v_qty>50 then raise exception 'Quantidade inválida';end if;
  select * into v_prod from public.pb_products where id=(v_rec.value->>'product_id')::bigint and active=true;
  if not found then raise exception 'Produto indisponível';end if;
  v_sub := v_sub + round(v_prod.price*v_qty,2);
 end loop;
 select coalesce((select value::numeric from public.pb_store where key='minimum_order'),20) into v_min;
 if p_require_minimum and v_sub<v_min then raise exception 'Pedido abaixo do mínimo';end if;
 v_total:=round(v_sub+p_fee,2);
 insert into public.pb_orders(customer,phone,address,distance,fee,subtotal,total,payment,status)
 values(trim(p_customer),trim(p_phone),case when p_delivery then trim(p_address) else 'RETIRADA NO BALCÃO' end,
 p_distance,p_fee,v_sub,v_total,p_payment,'Recebido') returning id into v_order;
 for v_rec in select * from jsonb_array_elements(p_items) loop
  v_qty:=(v_rec.value->>'qty')::integer;
  select * into v_prod from public.pb_products where id=(v_rec.value->>'product_id')::bigint and active=true;
  insert into public.pb_order_items(order_id,name,qty,price) values(v_order,v_prod.name,v_qty,v_prod.price);
 end loop;
 return jsonb_build_object('id',v_order,'total',v_total,'fee',p_fee,'km',p_distance);
end $$;
revoke all on function public.pb_place_order(text,text,text,text,jsonb,boolean,numeric,numeric,boolean) from public,anon,authenticated;
grant execute on function public.pb_place_order(text,text,text,text,jsonb,boolean,numeric,numeric,boolean) to service_role;
